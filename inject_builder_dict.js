      datasetsToAcquire: "\${builderTranslations[loc].datasetsToAcquire}",
      requiredDataSource: "\${builderTranslations[loc].requiredDataSource}",
      premium: "\${builderTranslations[loc].premium}",
      high: "\${builderTranslations[loc].high}",
      standard: "\${builderTranslations[loc].standard}",
      basic: "\${builderTranslations[loc].basic}",
      summQualityTier: "\${builderTranslations[loc].summQualityTier}",
      summSelectedSource: "\${builderTranslations[loc].summSelectedSource}",
      summVolume: "\${builderTranslations[loc].summVolume}",
      summPremiumPrice: "\${builderTranslations[loc].summPremiumPrice}",
      summMultiplier: "\${builderTranslations[loc].summMultiplier}",
